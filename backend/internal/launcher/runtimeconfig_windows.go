package launcher

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// The Web UI reads these values at page load from runtime-config.js, which the Docker image writes
// at container start; the keys must match frontend/src/constants.ts.
func writeFrontendRuntimeConfig(uiBuildFolder string) error {
	isEmailConfigured := "false"
	if strings.TrimSpace(os.Getenv("SMTP_HOST")) != "" {
		isEmailConfigured = "true"
	}

	runtimeConfig := map[string]string{
		"GITHUB_CLIENT_ID":              os.Getenv("GITHUB_CLIENT_ID"),
		"GOOGLE_CLIENT_ID":              os.Getenv("GOOGLE_CLIENT_ID"),
		"IS_EMAIL_CONFIGURED":           isEmailConfigured,
		"CLOUDFLARE_TURNSTILE_SITE_KEY": os.Getenv("CLOUDFLARE_TURNSTILE_SITE_KEY"),
		"CONTAINER_ARCH":                "amd64",
	}

	runtimeConfigJSON, err := json.MarshalIndent(runtimeConfig, "", "  ")
	if err != nil {
		return err
	}

	content := "// Generated by the Databasus launcher at startup; edits are overwritten.\n" +
		"window.__RUNTIME_CONFIG__ = " + string(runtimeConfigJSON) + ";\n"

	runtimeConfigPath := filepath.Join(uiBuildFolder, "runtime-config.js")
	if err := os.WriteFile(runtimeConfigPath, []byte(content), 0o644); err != nil {
		return fmt.Errorf("write %s: %w", runtimeConfigPath, err)
	}

	return nil
}
